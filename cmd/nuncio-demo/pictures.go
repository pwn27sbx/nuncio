// gradient is the demo photo: a colour gradient of width x height.
func gradient(width, height int) image.Image {
	img := image.NewRGBA(image.Rect(0, 0, width, height))
	for y := 0; y < height; y++ {
		for x := 0; x < width; x++ {
			img.Set(x, y, color.RGBA{R: uint8(x * 255 / (width - 1)), G: uint8(y * 255 / (height - 1)), B: 160, A: 255})
		}
	}
	return img
}

// photoThumb is the small JPEG an image message embeds, as WhatsApp's JPEGThumbnail.
func photoThumb() []byte {
	var b bytes.Buffer
	_ = jpeg.Encode(&b, gradient(48, 32), &jpeg.Options{Quality: 70})
	return b.Bytes()
}

// stickerThumb is the small PNG a sticker message embeds: a disc of fill on a transparent square.
func stickerThumb(fill color.RGBA) []byte {
	const n = 64
	img := image.NewRGBA(image.Rect(0, 0, n, n))
	for y := 0; y < n; y++ {
		for x := 0; x < n; x++ {
			dx, dy := float64(x)-31.5, float64(y)-31.5
			switch r := dx*dx + dy*dy; {
			case r < 26*26:
				img.Set(x, y, fill)
			case r < 30*30:
				img.Set(x, y, color.RGBA{R: 255, G: 255, B: 255, A: 255})
			}
		}
	}
	var b bytes.Buffer
	_ = png.Encode(&b, img)
	return b.Bytes()
}

